import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function collectSlugs(relativeDir) {
  const dir = path.join(root, relativeDir);
  if (!fs.existsSync(dir)) return [];

  const slugs = new Set();
  for (const file of fs.readdirSync(dir)) {
    const match = file.match(/^(.+)\.(?:jpe?g|webp|png|avif)$/i);
    if (match) slugs.add(match[1]);
  }

  return [...slugs].sort();
}

function writeManifest(folder) {
  const slugs = collectSlugs(`public/images/${folder}`);
  const lines = slugs.map((slug) => `  "${slug}",`).join("\n");
  return `export const ${folder.toUpperCase()}_PROFILE_IMAGES = new Set([\n${lines}\n]);\n`;
}

const output = `/* Generated by scripts/generate-profile-images.mjs — do not edit by hand. */
import { profileSlug } from "./profile-utils.js";

${writeManifest("team")}
${writeManifest("board")}

const MANIFESTS = {
  team: TEAM_PROFILE_IMAGES,
  board: BOARD_PROFILE_IMAGES,
};

export function hasProfilePhoto(name, folder, explicitImage) {
  if (explicitImage) return true;
  const slug = profileSlug(name);
  return MANIFESTS[folder]?.has(slug) ?? false;
}

export function getProfileImageCandidates(name, folder, explicitImage) {
  const candidates = [];
  if (explicitImage) {
    candidates.push(explicitImage);
    return candidates;
  }

  const slug = profileSlug(name);
  const manifest = MANIFESTS[folder];
  if (!manifest?.has(slug)) return candidates;

  candidates.push(\`/images/\${folder}/\${slug}.webp\`);
  candidates.push(\`/images/\${folder}/\${slug}.jpg\`);
  return candidates;
}
`;

const outPath = path.join(root, "js/profile-images.js");
fs.writeFileSync(outPath, output);
console.log(`Wrote ${outPath}`);
